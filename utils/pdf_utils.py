# ---------------------------------------------------------
# PDF TEXT EXTRACTION
# ---------------------------------------------------------

def pdf_to_text(pdf_bytes):
    """
    Extract text from all pages of a PDF.
    """

    document = fitz.open(
        stream=pdf_bytes,
        filetype="pdf"
    )

    pages = []

    for page_number, page in enumerate(document):
        page_text = page.get_text("text")

        pages.append({
            "page_number": page_number + 1,
            "text": page_text
        })

    document.close()

    return pages


def extract_page_text(pdf_bytes, page_number):
    """
    Extract text from a selected PDF page.

    page_number is zero-based.
    """

    document = fitz.open(
        stream=pdf_bytes,
        filetype="pdf"
    )

    if page_number < 0 or page_number >= len(document):
        document.close()
        return ""

    page = document.load_page(page_number)

    text = page.get_text("text")

    document.close()

    return text.strip()


# ---------------------------------------------------------
# PDF PAGE RENDERING
# ---------------------------------------------------------

def render_pdf_page(pdf_bytes, page_number, zoom=1.5):
    """
    Render one PDF page as a PNG image.

    page_number is zero-based.
    """

    document = fitz.open(
        stream=pdf_bytes,
        filetype="pdf"
    )

    if page_number < 0 or page_number >= len(document):
        document.close()
        return None

    page = document.load_page(page_number)

    matrix = fitz.Matrix(zoom, zoom)

    pixmap = page.get_pixmap(
        matrix=matrix,
        alpha=False
    )

    image_bytes = pixmap.tobytes("png")

    document.close()

    return image_bytes


def _render_pdf_pages(
    pdf_bytes,
    page_number,
    zoom
):
    """
    Display the currently selected PDF page.
    """

    image_bytes = render_pdf_page(
        pdf_bytes,
        page_number,
        zoom
    )

    if image_bytes is None:
        st.error("Unable to render the selected page.")
        return

    st.image(
        image_bytes,
        caption=f"Page {page_number + 1}",
        use_container_width=True
    )


